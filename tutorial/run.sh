#!/usr/bin/env bash
# Regenerates everything the tutorial shows, from scratch:
#
#   1. rebuilds a throwaway database (scenex_tutorial) with Common Ground (from
#      the export in ../data/common-ground, see common_ground/export.sh) and
#      Mars Colony,
#   2. starts Scenex on port 4100 against it,
#   3. captures the screenshots into docs/tutorial/images/ and writes the
#      generated reference pages,
#   4. with --video, also records the narrated screencast (see video/).
#
#     tutorial/run.sh               screenshots + reference pages
#     tutorial/run.sh --video       … plus the video
#     tutorial/run.sh --video-only  only the video
#     tutorial/run.sh --serve       only rebuild the database and serve it, to
#                                   click along (log in as director@scenex.example
#                                   / common-ground-2026)
#
# Your normal dev database is never touched.
set -euo pipefail

cd "$(dirname "$0")/.."
export SCENEX_DEV_DATABASE=scenex_tutorial
export PORT=4100
export MIX_ENV=dev
MODE="${1:-}"

if lsof -iTCP:$PORT -sTCP:LISTEN >/dev/null 2>&1; then
  echo "Port $PORT is busy — stop whatever runs there first." >&2
  exit 1
fi

(cd tutorial && [ -d node_modules ] || (npm install --no-audit --no-fund && npx playwright install chromium))

reset_database() {
  echo "▸ Resetting the tutorial database"
  mix ecto.drop --quiet --force-drop >/dev/null
  mix ecto.create --quiet
  mix ecto.migrate --quiet >/dev/null
  mix run tutorial/setup.exs 2>&1 | grep -E "Loaded Common Ground|Seeded Mars Colony"
}

reset_database

if [[ "$MODE" == "--serve" ]]; then
  echo "▸ Serving on http://localhost:$PORT (Ctrl-C to stop)"
  exec mix phx.server
fi

echo "▸ Starting Scenex on :$PORT"
mix phx.server >/tmp/scenex-tutorial-server.log 2>&1 &
SERVER=$!
trap 'kill $SERVER 2>/dev/null || true' EXIT
for _ in $(seq 1 60); do
  curl -sf "http://localhost:$PORT/" >/dev/null && break
  sleep 1
done

if [[ "$MODE" != "--video-only" ]]; then
  echo "▸ Capturing screenshots"
  (cd tutorial && node capture.mjs)
  cp priv/repo/mars_colony/jezero-crater.png docs/tutorial/images/

  echo "▸ Writing the reference pages"
  mix run tutorial/reference.exs "COMMON GROUND" docs/tutorial/common-ground-content.md common-ground.md 2>&1 | grep Wrote
  mix run tutorial/reference.exs mars_colony docs/tutorial/mars-colony-content.md mars-colony.md 2>&1 | grep Wrote

  echo "▸ Running the Mars Colony balance check"
  {
    echo "# Mars Colony — balance report"
    echo
    echo "> Generated by \`priv/repo/balance_mars_colony.exs\` (via \`tutorial/run.sh\`)."
    echo "> Each run plays the whole scenario through the live-session code."
    echo
    echo "[← Mars Colony](mars-colony.md) · [Contents](index.md)"
    echo
    echo '```text'
    mix run priv/repo/balance_mars_colony.exs 5000 2>&1 | grep -v '^\[info\]'
    echo '```'
  } > docs/tutorial/mars-colony-balance.md
fi

if [[ "$MODE" == "--video" || "$MODE" == "--video-only" ]]; then
  # The screenshot run leaves sessions behind; the video starts clean. (The
  # server keeps running — only the data underneath is replaced.)
  if [[ "$MODE" == "--video" ]]; then
    kill $SERVER 2>/dev/null || true
    wait $SERVER 2>/dev/null || true
    reset_database
    mix phx.server >/tmp/scenex-tutorial-server.log 2>&1 &
    SERVER=$!
    for _ in $(seq 1 60); do
      curl -sf "http://localhost:$PORT/" >/dev/null && break
      sleep 1
    done
  fi
  echo "▸ Recording the video"
  (cd tutorial && node video/record.mjs && node video/assemble.mjs)
fi

echo "▸ Done"
